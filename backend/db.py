"""Postgres storage (Supabase) for the fictional Bright Smile Dental office.

Set DATABASE_URL to a Supabase connection string (Project -> Connect -> Session
pooler). Any other Postgres works too.

Schemas keep runs apart inside ONE database:
    public              the app (CLI, API, UI)
    test_<random>       one per pytest run, dropped afterwards
    eval_<random>       one per eval run, dropped afterwards
so tests and evals can reset freely without touching the app's data.

Safety rules live in the database itself: UNIQUE(slot_id) on appointments
blocks double booking, and a CHECK limits approval decisions.

Only fictional data is stored. Patients are aliases like "Test Patient A".
"""

import random
import re
import threading
import uuid
from datetime import date, datetime, timedelta

import psycopg
from psycopg.rows import dict_row

PROVIDERS = [
    ("P1", "Dr. Rivera", "general dentistry"),
    ("P2", "Dr. Chen", "general dentistry"),
    ("P3", "Dr. Okafor", "hygienist (cleanings)"),
]
PATIENTS = ["Test Patient A", "Test Patient B", "Test Patient C", "Test Patient D"]
TIMES = ["09:00", "09:30", "10:00", "10:30", "11:00", "11:30",
         "13:00", "13:30", "14:00", "14:30", "15:00", "15:30", "16:00", "16:30"]
TABLES = ["approval_requests", "appointments", "approvals", "slots", "patients", "providers"]  # drop order

SCHEMA_SQL = """
CREATE TABLE providers (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    specialty TEXT NOT NULL
);
CREATE TABLE patients (
    alias TEXT PRIMARY KEY,                   -- fictional only, e.g. 'Test Patient A'
    user_id UUID UNIQUE                       -- Supabase Auth user, if this patient signs in
);
CREATE TABLE slots (
    id TEXT PRIMARY KEY,                      -- e.g. S-20261124-0900-P1
    provider_id TEXT NOT NULL REFERENCES providers(id),
    date TEXT NOT NULL,                       -- YYYY-MM-DD
    start_time TEXT NOT NULL,                 -- HH:MM
    duration_min INTEGER NOT NULL
);
CREATE TABLE approvals (                  -- audit log: one row per HUMAN decision
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action TEXT NOT NULL DEFAULT 'book' CHECK (action IN ('book', 'cancel', 'reschedule')),
    appointment_id BIGINT,                    -- the appointment being cancelled / rescheduled
    slot_id TEXT NOT NULL,                    -- slot being booked (book, reschedule) or freed (cancel)
    patient_alias TEXT NOT NULL,
    reason TEXT NOT NULL,
    decision TEXT NOT NULL CHECK (decision IN ('approved', 'denied')),
    decided_by TEXT NOT NULL,                 -- a human: cli | staff:<email> | ui-staff | test | seed
    decided_at TEXT NOT NULL
);
CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id TEXT NOT NULL REFERENCES slots(id),
    patient_alias TEXT NOT NULL REFERENCES patients(alias) ON UPDATE CASCADE,
    reason TEXT NOT NULL,
    approval_id BIGINT NOT NULL REFERENCES approvals(id),
    status TEXT NOT NULL DEFAULT 'booked' CHECK (status IN ('booked', 'cancelled')),
    created_at TEXT NOT NULL,
    cancelled_at TEXT,
    cancel_approval_id BIGINT REFERENCES approvals(id)
);
-- No double booking: at most ONE active (booked) appointment per slot. Cancelled rows stay for the audit trail.
CREATE UNIQUE INDEX one_active_booking_per_slot ON appointments(slot_id) WHERE status = 'booked';

CREATE TABLE approval_requests (          -- the staff queue: what the agent asked a human to approve
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL,
    patient_alias TEXT NOT NULL,
    action TEXT NOT NULL CHECK (action IN ('book', 'cancel', 'reschedule')),
    request TEXT NOT NULL,                    -- JSON: date, time, provider, reason, patient's own words
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'denied', 'expired')),
    created_at TEXT NOT NULL,
    decided_at TEXT,
    decided_by TEXT,
    approval_id BIGINT REFERENCES approvals(id),
    outcome TEXT                              -- e.g. verified | not_saved: slot taken
);
"""

# Supabase only: let a signed-in patient's browser read ITS OWN appointments directly,
# enforced by Postgres Row Level Security (not by our Python code). Skipped on plain Postgres.
RLS_POLICIES_SQL = """
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated')
     AND to_regprocedure('auth.uid()') IS NOT NULL THEN
    GRANT SELECT ON providers, slots, patients, appointments TO authenticated;
    CREATE POLICY "signed-in users read providers" ON providers FOR SELECT TO authenticated USING (true);
    CREATE POLICY "signed-in users read slots" ON slots FOR SELECT TO authenticated USING (true);
    CREATE POLICY "patients read their own profile" ON patients FOR SELECT TO authenticated
      USING (user_id = auth.uid());
    CREATE POLICY "patients read their own appointments" ON appointments FOR SELECT TO authenticated
      USING (patient_alias IN (SELECT alias FROM patients WHERE user_id = auth.uid()));
  END IF;
END $$;
"""

_SCHEMA_NAME = re.compile(r"^[a-z_][a-z0-9_]{0,62}$")


class IntegrityError(Exception):
    """A database constraint was violated (e.g. the slot was already booked)."""


class DatabaseError(RuntimeError):
    """The database could not be reached or is not configured."""


def normalize_url(url: str) -> str:
    """Percent-encode the password so characters like @ # / ? in it don't break the URL.

    Supabase shows the string with a [YOUR-PASSWORD] placeholder; people paste their
    raw password in, and an '@' in it would otherwise be read as the host separator.
    """
    from urllib.parse import quote, unquote

    scheme, sep, rest = url.partition("://")
    if not sep or "@" not in rest:
        return url
    userinfo, host = rest.rsplit("@", 1)          # the LAST @ separates credentials from host
    user, colon, password = userinfo.partition(":")
    if not colon:
        return url
    return f"{scheme}://{user}:{quote(unquote(password), safe='')}@{host}"


def _scrub(message: str, url: str) -> str:
    """Remove any credential fragment from an error message before it is shown or logged."""
    rest = url.partition("://")[2]
    userinfo = rest.rsplit("@", 1)[0] if "@" in rest else ""
    for piece in sorted({p for p in re.split(r"[:@]", userinfo) if len(p) >= 3} | {userinfo}, key=len, reverse=True):
        if piece:
            message = message.replace(piece, "***")
    return message


class Database:
    """Thin wrapper over one psycopg connection. Rows are plain dicts.

    SQL in the project is written with '?' placeholders; they become '%s' here.
    prepare_threshold=None keeps it compatible with Supabase's poolers.
    """

    def __init__(self, url: str, schema: str = "public"):
        if not url:
            raise DatabaseError("DATABASE_URL is not set. Add your Supabase connection string to .env "
                                "(Project -> Connect -> Session pooler).")
        if not _SCHEMA_NAME.match(schema):
            raise DatabaseError(f"Invalid schema name '{schema}'.")
        self._raw_url = url
        self._url, self.schema = normalize_url(url), schema
        host = url.rsplit("@", 1)[-1].split("/")[0].split(":")[0] if "@" in url else "postgres"
        self.label = ("supabase" if "supabase" in host else f"postgres ({host})") + ("" if schema == "public" else f" [{schema}]")
        self._lock = threading.RLock()
        self._in_tx = False
        self._connect()

    def _connect(self):
        try:
            self.conn = psycopg.connect(self._url, autocommit=True, row_factory=dict_row,
                                        prepare_threshold=None, connect_timeout=15)
        except (psycopg.OperationalError, psycopg.ProgrammingError) as e:
            first_line = _scrub(_scrub(str(e).splitlines()[0], self._raw_url), self._url)
            hint = ""
            if ".supabase.co" in self._url and "pooler" not in self._url:
                hint = (" Tip: this is Supabase's 'Direct connection' string, which needs IPv6. Use the "
                        "'Session pooler' string from Connect instead.")
            raise DatabaseError(f"Cannot connect to the database: {first_line}.{hint}") from None
        if self.schema != "public":
            self.conn.execute(f'CREATE SCHEMA IF NOT EXISTS "{self.schema}"')
        self.conn.execute(f'SET search_path TO "{self.schema}"')

    @staticmethod
    def _pg(sql: str) -> str:
        return sql.replace("?", "%s")

    def _execute(self, fn):
        """Run fn(conn); reconnect once if Supabase dropped an idle connection."""
        with self._lock:
            try:
                return fn(self.conn)
            except psycopg.IntegrityError as e:
                raise IntegrityError(str(e)) from e
            except psycopg.OperationalError:
                if self._in_tx:
                    raise
                self._connect()
                return fn(self.conn)

    def query(self, sql: str, params: tuple = ()) -> list[dict]:
        def go(conn):
            # No params -> send plain SQL, so a literal % (e.g. LIKE 'x%') is not read as a placeholder.
            cur = conn.execute(self._pg(sql), params) if params else conn.execute(sql)
            return list(cur.fetchall()) if cur.description else []
        return self._execute(go)

    def one(self, sql: str, params: tuple = ()) -> dict | None:
        rows = self.query(sql, params)
        return rows[0] if rows else None

    def run(self, sql: str, params: tuple = ()) -> None:
        self._execute(lambda conn: conn.execute(self._pg(sql), params) if params else conn.execute(sql))

    def insert(self, sql: str, params: tuple = ()) -> int:
        """INSERT ... RETURNING id; returns the new id."""
        return self.one(sql + " RETURNING id", params)["id"]

    def run_many(self, sql: str, rows: list[tuple]) -> None:
        self._execute(lambda conn: conn.cursor().executemany(self._pg(sql), rows))

    def run_script(self, sql: str) -> None:
        self._execute(lambda conn: conn.execute(sql))

    def has_schema(self) -> bool:
        """True if the CURRENT table layout exists. An older layout counts as missing, so it gets re-created."""
        return self.one("SELECT to_regclass(?) IS NOT NULL AND to_regclass(?) IS NOT NULL AS ok",
                        (f'"{self.schema}".appointments', f'"{self.schema}".approval_requests'))["ok"]

    def transaction(self):
        db = self

        class _Tx:
            def __enter__(self):
                db._lock.acquire()
                db._in_tx = True
                self.tx = db.conn.transaction()
                self.tx.__enter__()

            def __exit__(self, *exc):
                try:
                    self.tx.__exit__(*exc)
                finally:
                    db._in_tx = False
                    db._lock.release()

        return _Tx()

    def drop_schema(self) -> None:
        """Remove a private test/eval schema. Refuses to drop 'public'."""
        if self.schema == "public":
            raise DatabaseError("Refusing to drop the public schema.")
        self.run_script(f'DROP SCHEMA IF EXISTS "{self.schema}" CASCADE')

    def close(self) -> None:
        self.conn.close()


def private_schema(prefix: str) -> str:
    """A fresh schema name for an isolated run, e.g. test_3f9a1c2b."""
    return f"{prefix}_{uuid.uuid4().hex[:8]}"


def business_days(start: date, count: int) -> list[date]:
    """The next `count` weekdays strictly after `start`."""
    days, d = [], start
    while len(days) < count:
        d += timedelta(days=1)
        if d.weekday() < 5:
            days.append(d)
    return days


def create_schema(db: Database) -> None:
    db.run_script(f"DROP TABLE IF EXISTS {', '.join(TABLES)} CASCADE;")
    db.run_script(SCHEMA_SQL)
    # Supabase exposes the public schema over its REST API. Row Level Security
    # with no policies blocks that API; this app connects as the table owner.
    db.run_script("".join(f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY;" for t in TABLES))
    db.run_script(RLS_POLICIES_SQL)


def seed(db: Database, today: date, days: int = 10, rng_seed: int = 42) -> None:
    """Create a fresh fictional schedule starting the weekday after `today`.

    Deterministic for a given (today, rng_seed). About a quarter of slots are
    pre-booked. Dr. Rivera's whole first Tuesday morning is always booked so the
    'unavailable slot' demo is predictable.
    """
    create_schema(db)
    rng = random.Random(rng_seed)
    seeded_at = datetime(today.year, today.month, today.day).isoformat()
    first_tuesday = next(d for d in business_days(today, days) if d.weekday() == 1)

    slots, booked = [], []
    for d in business_days(today, days):
        for pid, _, _ in PROVIDERS:
            for t in TIMES:
                slot_id = f"S-{d:%Y%m%d}-{t.replace(':', '')}-{pid}"
                slots.append((slot_id, pid, d.isoformat(), t, 30))
                if (d == first_tuesday and pid == "P1" and t < "12:00") or rng.random() < 0.25:
                    booked.append(slot_id)

    with db.transaction():  # batched, important over the network to Supabase
        db.run_many("INSERT INTO providers VALUES (?,?,?)", PROVIDERS)
        db.run_many("INSERT INTO patients (alias) VALUES (?)", [(p,) for p in PATIENTS])
        db.run_many("INSERT INTO slots VALUES (?,?,?,?,?)", slots)
        # Pre-existing bookings belong to a different fake patient. Approval ids are 1..n, in order.
        db.run_many("INSERT INTO approvals (id, slot_id, patient_alias, reason, decision, decided_by, decided_at)"
                    " VALUES (?,?,?,?,?,?,?)",
                    [(i + 1, s, "Test Patient D", "existing booking", "approved", "seed", seeded_at) for i, s in enumerate(booked)])
        db.run_many("INSERT INTO appointments (slot_id, patient_alias, reason, approval_id, created_at) VALUES (?,?,?,?,?)",
                    [(s, "Test Patient D", "existing booking", i + 1, seeded_at) for i, s in enumerate(booked)])
    # Explicit ids above; move the identity counter past them.
    db.run("SELECT setval(pg_get_serial_sequence('approvals', 'id'), (SELECT COALESCE(MAX(id), 1) FROM approvals))")


def reset_to_seed(db: Database) -> None:
    """Undo everything since seeding (fast, no re-seed): used between tests and eval runs."""
    with db.transaction():
        db.run("DELETE FROM approval_requests")
        db.run("DELETE FROM appointments WHERE approval_id IN (SELECT id FROM approvals WHERE decided_by <> 'seed')")
        db.run("UPDATE appointments SET status = 'booked', cancelled_at = NULL, cancel_approval_id = NULL"
               " WHERE status <> 'booked'")
        db.run("DELETE FROM approvals WHERE decided_by <> 'seed'")
        db.run("DELETE FROM patients WHERE alias NOT IN (?, ?, ?, ?)", tuple(PATIENTS))
    db.run("SELECT setval(pg_get_serial_sequence('approvals', 'id'), (SELECT COALESCE(MAX(id), 1) FROM approvals))")


def init_db(url: str, today: date, reset: bool = False, schema: str = "public") -> Database:
    """Connect, seeding the schema if it is empty or reset=True."""
    db = Database(url, schema)
    if reset or not db.has_schema():
        seed(db, today)
    return db
